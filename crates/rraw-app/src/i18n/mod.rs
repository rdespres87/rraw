#![forbid(unsafe_code)]

//! Strongly-typed, zero-allocation internationalization (i18n) engine for `rraw-app`.
//!
//! # Architecture & Guarantees
//! - **Zero Runtime Allocation**: All translations return `&'static str` literals with zero heap allocations.
//! - **Compile-time Exhaustiveness**: Translations are matched against `(Key, Language)` with zero wildcard `_ =>` fallbacks.
//!   Adding a new string key or language causes a compile error until all translations are provided.
//! - **Reactive O(1) Switching**: UI switches language instantly by mutating `app.layout_config.language`.
//! - **Persistence**: Language selection is saved to `~/.config/rraw/layout.json` via Serde.

use serde::{Deserialize, Serialize};
use std::fmt;

/// Supported application display languages.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    /// French (Français) - Default display language.
    #[default]
    Fr,
    /// English.
    En,
}

impl Language {
    /// All available languages.
    pub const ALL: [Self; 2] = [Self::Fr, Self::En];

    /// Two-letter ISO 639-1 code.
    #[must_use]
    pub const fn code(self) -> &'static str {
        match self {
            Self::Fr => "FR",
            Self::En => "EN",
        }
    }

    /// Full human-readable display name.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Fr => "Français",
            Self::En => "English",
        }
    }

    /// Cycle to the next language.
    #[must_use]
    pub const fn next(self) -> Self {
        match self {
            Self::Fr => Self::En,
            Self::En => Self::Fr,
        }
    }
}

impl fmt::Display for Language {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.code())
    }
}

