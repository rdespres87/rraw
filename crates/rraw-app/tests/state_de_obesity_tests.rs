//! TDD Verification Suite for Task 15.1: State De-Obesity & Domain Hierarchy.
//!
//! Validates:
//! 1. Composable domain sub-structs (`ToneGradingParams`, `ColorGradingParams`, `DenoiseSharpenParams`,
//!    `OpticsGradingParams`, `GeometryGradingParams`).
//! 2. `DarkroomGradingState` composition using these domain sub-structs.
//! 3. Serde `#[serde(flatten)]` backward and forward compatibility for `SidecarRecipe` with legacy `.rraw.json`.
//! 4. Snapshot roundtrips via `SidecarRecipe::from_state` and `apply_to`.

use rraw_app::state::{DarkroomGradingState, SidecarRecipe};
use rraw_color::DisplayTransform;

#[test]
fn test_state_de_obesity_substruct_composition() {
    let mut state = DarkroomGradingState::default();

    // Verify ToneGradingParams isolation
    state.tone.exposure_ev = 1.25;
    state.tone.contrast = 15.0;
    state.tone.highlights = -20.0;
    state.tone.shadows = 30.0;
    state.tone.blacks = -5.0;
    state.tone.saturation = 10.0;
    state.tone.vibrance = 5.0;

    assert_eq!(state.tone.exposure_ev, 1.25);
    assert_eq!(state.tone.contrast, 15.0);

    // Verify ColorGradingParams isolation
    state.color.kelvin = 6200.0;
    state.color.tint = 8.0;
    state.color.display_transform = DisplayTransform::OpenDrt;
    state.color.is_monochrome = false;

    assert_eq!(state.color.kelvin, 6200.0);
    assert_eq!(state.color.display_transform, DisplayTransform::OpenDrt);

    // Verify DenoiseSharpenParams isolation
    state.denoise_sharpen.wavelet_denoise_sigma = 1.5;
    state.denoise_sharpen.color_denoise = 30.0;
    state.denoise_sharpen.luma_denoise = 10.0;
    state.denoise_sharpen.capture_sharpening_amount = 0.8;

    assert_eq!(state.denoise_sharpen.color_denoise, 30.0);

    // Verify OpticsGradingParams isolation
    state.optics.lens_distortion_strength = 90.0;
    state.optics.defringe_purple_amount = 25.0;
    assert_eq!(state.optics.lens_distortion_strength, 90.0);

    // Verify GeometryGradingParams isolation
    state.geometry.crop_enabled = true;
    state.geometry.crop_left = 0.1;
    state.geometry.crop_right = 0.9;
    assert_eq!(state.geometry.crop_left, 0.1);
}

#[test]
fn test_sidecar_recipe_legacy_flat_json_backward_compatibility(
) -> Result<(), Box<dyn std::error::Error>> {
    // Real legacy flat JSON generated by previous versions of Rraw
    let legacy_json = r#"{
        "schema_version": 1,
        "preset": "custom",
        "exposure_ev": 1.5,
        "contrast": 20.0,
        "highlights": -30.0,
        "shadows": 40.0,
        "blacks": -10.0,
        "saturation": 12.0,
        "vibrance": 8.0,
        "kelvin": 6500.0,
        "tint": -5.0,
        "display_transform": "AgX",
        "wavelet_denoise_sigma": 1.2,
        "color_denoise": 25.0,
        "luma_denoise": 5.0,
        "capture_sharpening_amount": 0.7,
        "optical_tab": "Profile",
        "lens_profile_auto": true,
        "lens_distortion_strength": 100.0,
        "lens_vignette_strength": 100.0,
        "lens_ca_strength": 100.0,
        "distortion_correction": true,
        "distortion_amount": 0.0,
        "chromatic_aberration_correction": true,
        "defringe_purple_amount": 10.0,
        "defringe_green_amount": 5.0,
        "defringe_threshold": 0.08,
        "defringe_preview_mask": false,
        "vignette_correction": true,
        "vignette_amount": 50.0,
        "creative_vignette_amount": 0.0,
        "creative_vignette_midpoint": 50.0,
        "creative_vignette_feather": 50.0,
        "creative_vignette_roundness": 0.0,
        "is_monochrome": false,
        "rating": 4,
        "crop_enabled": true,
        "crop_aspect": "Ratio3x2",
        "crop_left": 0.05,
        "crop_top": 0.05,
        "crop_right": 0.95,
        "crop_bottom": 0.95,
        "rotation_degrees": 1.5,
        "flip_horizontal": false,
        "flip_vertical": false,
        "geometry_enabled": true,
        "keystone_vertical": 0.0,
        "keystone_horizontal": 0.0,
        "custom_lut_path": null,
        "custom_lut_strength": 1.0,
        "semantic_masks": [],
        "local_masks": [],
        "smart_lighting": {
            "mode": "slight",
            "intensity": 1.0,
            "custom_shadow_lift": 0.0,
            "custom_highlight_compression": 0.0
        }
    }"#;

    // Deserialization into flattened recipe
    let recipe: SidecarRecipe = serde_json::from_str(legacy_json)?;

    assert_eq!(recipe.rating, 4);
    assert_eq!(recipe.tone.exposure_ev, 1.5);
    assert_eq!(recipe.tone.contrast, 20.0);
    assert_eq!(recipe.tone.highlights, -30.0);
    assert_eq!(recipe.tone.shadows, 40.0);
    assert_eq!(recipe.tone.blacks, -10.0);
    assert_eq!(recipe.tone.saturation, 12.0);
    assert_eq!(recipe.tone.vibrance, 8.0);
    assert_eq!(recipe.color.kelvin, 6500.0);
    assert_eq!(recipe.color.tint, -5.0);
    assert_eq!(recipe.color.display_transform, "AgX");
    assert_eq!(recipe.denoise_sharpen.wavelet_denoise_sigma, 1.2);
    assert_eq!(recipe.denoise_sharpen.color_denoise, 25.0);
    assert_eq!(recipe.optics.lens_distortion_strength, 100.0);
    assert_eq!(recipe.optics.defringe_purple_amount, 10.0);
    assert!(recipe.geometry.crop_enabled);
    assert_eq!(recipe.geometry.crop_left, 0.05);

    // Apply to DarkroomGradingState
    let mut state = DarkroomGradingState::default();
    recipe.apply_to(&mut state);

    assert_eq!(state.tone.exposure_ev, 1.5);
    assert_eq!(state.color.kelvin, 6500.0);
    assert_eq!(state.color.display_transform, DisplayTransform::AgX);
    assert_eq!(state.geometry.crop_left, 0.05);

    // Re-serialize and verify it still outputs flat JSON keys
    let serialized = serde_json::to_string(&recipe)?;
    let v: serde_json::Value = serde_json::from_str(&serialized)?;
    assert!(
        v.get("exposure_ev").is_some(),
        "Flat key 'exposure_ev' must be preserved at root"
    );
    assert!(
        v.get("kelvin").is_some(),
        "Flat key 'kelvin' must be preserved at root"
    );
    assert!(
        v.get("crop_left").is_some(),
        "Flat key 'crop_left' must be preserved at root"
    );

    Ok(())
}
